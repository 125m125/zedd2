#!/usr/bin/env node
/**
 * Generates latest.yml from the latest Squirrel build output.
 * Usage: node scripts/generate-latest-yml.js [--publish]
 *
 * This script:
 * 1. Finds the latest .nupkg in the squirrel output directory
 * 2. Generates latest.yml (electron-updater format)
 * 3. Optionally uploads latest.yml to the GitHub release (with --publish flag)
 */
const crypto = require('crypto')
const fs = require('fs')
const https = require('https')
const path = require('path')

const SQUIRREL_DIR = path.join(__dirname, '..', 'out', 'make', 'squirrel.windows', 'x64')
const OWNER = '125m125'
const REPO = 'zedd2'

function sha512(filePath) {
  return new Promise((resolve, reject) => {
    const hash = crypto.createHash('sha512')
    const stream = fs.createReadStream(filePath)
    stream.on('data', (chunk) => hash.update(chunk))
    stream.on('end', () => resolve(hash.digest('hex')))
    stream.on('error', reject)
  })
}

function githubRequest(method, urlPath, body) {
  return new Promise((resolve, reject) => {
    const url = new URL(urlPath, 'https://api.github.com')
    const req = https.request(
      {
        hostname: url.hostname,
        port: 443,
        path: url.pathname,
        method,
        headers: {
          'User-Agent': 'zedd-app-updater',
          'Content-Type': 'application/json',
          Accept: 'application/vnd.github.v3+json',
          Authorization: `token ${process.env.GITHUB_TOKEN}`,
        },
      },
      (res) => {
        let data = ''
        res.on('data', (chunk) => (data += chunk))
        res.on('end', () => {
          if (res.statusCode >= 400) {
            reject(new Error(`GitHub API ${method} ${urlPath} failed: ${res.statusCode} ${data}`))
          } else {
            resolve(JSON.parse(data))
          }
        })
      },
    )
    if (body) req.write(JSON.stringify(body))
    req.end()
  })
}

async function uploadToRelease(latestYmlPath, version) {
  const tagName = `v${version}`
  console.log(`Uploading latest.yml to release ${tagName}...`)

  // Get the release
  const release = await githubRequest('GET', `/repos/${OWNER}/${REPO}/releases/tags/${tagName}`)

  const filename = path.basename(latestYmlPath)
  const fileSize = fs.statSync(latestYmlPath).size
  const fileContent = fs.readFileSync(latestYmlPath)

  // Upload the asset
  const uploadUrl = `${release.upload_url.split('{')[0]}?name=${encodeURIComponent(filename)}`
  console.log(`Upload URL: ${uploadUrl}`)

  await new Promise((resolve, reject) => {
    const url = new URL(uploadUrl)
    const req = https.request(
      {
        hostname: url.hostname,
        port: 443,
        path: url.pathname + url.search,
        method: 'POST',
        headers: {
          'User-Agent': 'zedd-app-updater',
          'Content-Type': 'application/octet-stream',
          Authorization: `token ${process.env.GITHUB_TOKEN}`,
        },
      },
      (res) => {
        let data = ''
        res.on('data', (chunk) => (data += chunk))
        res.on('end', () => {
          if (res.statusCode >= 400) {
            reject(new Error(`Upload failed: ${res.statusCode} ${data}`))
          } else {
            console.log('Upload successful')
            resolve(JSON.parse(data))
          }
        })
      },
    )
    req.write(fileContent)
    req.end()
  })
}

async function main() {
  if (!fs.existsSync(SQUIRREL_DIR)) {
    console.error(`Squirrel directory not found: ${SQUIRREL_DIR}`)
    console.error('Run `npm run make` first.')
    process.exit(1)
  }

  // Find the latest .nupkg (full version, not delta)
  const files = fs.readdirSync(SQUIRREL_DIR).filter((f) => f.endsWith('-full.nupkg'))
  if (files.length === 0) {
    console.error('No full .nupkg found in squirrel output directory')
    process.exit(1)
  }

  // Sort by version and get the latest
  const versionPattern = /zedd-?([0-9]+\.[0-9]+\.[0-9]+)-full\.nupkg/
  const versions = files
    .map((f) => {
      const m = f.match(versionPattern)
      return m ? { file: f, version: m[1] } : null
    })
    .filter(Boolean)
    .sort((a, b) => {
      const pa = a.version.split('.').map(Number)
      const pb = b.version.split('.').map(Number)
      return pa[0] - pb[0] || pa[1] - pb[1] || pa[2] - pb[2]
    })

  const latest = versions[versions.length - 1]
  const nupkgPath = path.join(SQUIRREL_DIR, latest.file)
  const version = latest.version
  const fileSize = fs.statSync(nupkgPath).size
  const sha = await sha512(nupkgPath)

  console.log(`Generating latest.yml for ${latest.file} (v${version}, ${fileSize} bytes)`)

  // Create latest.yml content
  const yml = `# Generated by electron-updater
version: ${version}
files:
  - url: ${latest.file}
    sha512: ${sha}
    size: ${fileSize}
releaseDate: ${new Date().toISOString()}
`

  const ymlPath = path.join(SQUIRREL_DIR, 'latest.yml')
  fs.writeFileSync(ymlPath, yml)
  console.log(`Written: ${ymlPath}`)
  console.log(yml)

  // Optionally upload to GitHub
  if (process.argv.includes('--publish')) {
    if (!process.env.GITHUB_TOKEN) {
      console.error('GITHUB_TOKEN environment variable is required for --publish')
      console.error('Get a token at: https://github.com/settings/tokens with repo scope')
      process.exit(1)
    }

    await uploadToRelease(ymlPath, version)
    console.log('latest.yml uploaded to GitHub release')
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})