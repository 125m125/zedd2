/**
 * Forge plugin that:
 * 1. Cleans old .nupkg files from the squirrel make directory before each make
 *    (keeps only RELEASES and the current version's full nupkg)
 * 2. Generates latest.yml after make so electron-updater can discover updates
 */
const crypto = require('crypto')
const fs = require('fs')
const path = require('path')

const namedHookWithTaskFn = require('@electron-forge/plugin-base').namedHookWithTaskFn

module.exports = class GenerateLatestYmlPlugin {
  constructor(config) {
    this.config = config || {}
    this.name = 'GenerateLatestYmlPlugin'
    this.__isElectronForgePlugin = true
  }

  init(dir, config) {
    this.dir = dir
    this.forgeConfig = config.config
    this._resolvedHooks = {
      // Before make: clean old .nupkg files so they don't accumulate
      preMake: namedHookWithTaskFn(
        async (task) => {
          if (process.platform !== 'win32') return
          const squirrelDir = path.join(this.dir, 'out', 'make', 'squirrel.windows', 'x64')
          if (!fs.existsSync(squirrelDir)) return

          task.output = `Cleaning old .nupkg files from ${squirrelDir}`
          const files = fs.readdirSync(squirrelDir)
          for (const f of files) {
            if (f.endsWith('.nupkg') && f !== 'RELEASES') {
              fs.unlinkSync(path.join(squirrelDir, f))
            }
          }
          task.output = `Cleaned ${squirrelDir} (removed old .nupkg files)`
        },
        'clean-nupkg',
      ),
      // After make: generate latest.yml and add it to the output artifacts
      postMake: [
        {
          label: 'generate-latest-yml',
          task: async ({ makeResults }) => {
            if (process.platform !== 'win32') return makeResults

            for (const result of makeResults) {
              const squirrelDir = path.join(this.dir, 'out', 'make', 'squirrel.windows', 'x64')
              if (!fs.existsSync(squirrelDir)) continue

              const artifacts = result.artifacts
              const nupkgFile = artifacts.find((a) => a.endsWith('.nupkg'))
              if (!nupkgFile) continue

              // Extract version from nupkg filename: zedd-X.Y.Z-full.nupkg
              const baseName = path.basename(nupkgFile)
              const versionMatch = baseName.match(/zedd-?([0-9]+\.[0-9]+\.[0-9]+)-full\.nupkg/)
              if (!versionMatch) continue

              const version = versionMatch[1]

              // Compute sha512 of the nupkg
              const hash = crypto.createHash('sha512')
              const data = fs.readFileSync(nupkgFile)
              hash.update(data)
              const sha = hash.digest('hex')

              // Generate latest.yml content (electron-updater format)
              const latestYml = `# Generated by electron-updater
version: ${version}
files:
  - url: ${baseName.replace('-full.nupkg', '.nupkg')}
    sha512: ${sha}
    size: ${fs.statSync(nupkgFile).size}
releaseDate: ${new Date().toISOString()}
`

              const ymlPath = path.join(squirrelDir, 'latest.yml')
              fs.writeFileSync(ymlPath, latestYml)

              // Add latest.yml to the artifacts so the publisher uploads it
              artifacts.push(ymlPath)

              console.log(`[latest-yml] Generated ${ymlPath} for v${version}`)
            }

            return makeResults
          },
        },
      ],
    }
  }

  getHooks() {
    return this._resolvedHooks
  }
}